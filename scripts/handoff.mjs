/**
 * Refresh the machine-written snapshot in docs/handoff/CURRENT.md.
 *
 * The handoff doc has two kinds of content: prose written by whoever is
 * handing off (status, next steps, open decisions), and facts that go stale
 * the moment someone forgets to update them (branch, HEAD, uncommitted files,
 * whether the gates pass). This script owns the second kind. It only rewrites
 * the block between the SNAPSHOT markers and leaves the prose alone.
 *
 *   node scripts/handoff.mjs            rewrite the snapshot in place
 *   node scripts/handoff.mjs --gates    also run lint/build/diff-check and record results
 *   node scripts/handoff.mjs --stdout   print the updated doc instead of writing it
 *                                       (used by the harness `handoff` task, which
 *                                       writes it through its finalize gate)
 */
import { execSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DOC = path.join(ROOT, "docs", "handoff", "CURRENT.md");
const START = "<!-- SNAPSHOT:START (generated by scripts/handoff.mjs; edits here are overwritten) -->";
const END = "<!-- SNAPSHOT:END -->";

const args = new Set(process.argv.slice(2));

// Only trailing whitespace is trimmed: `status --porcelain` lines start with a
// meaningful space (" M" = modified but unstaged).
const git = (cmd) => {
  try {
    return execSync(`git ${cmd}`, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trimEnd();
  } catch {
    return "";
  }
};

const gate = (name, cmd) => {
  try {
    execSync(cmd, { cwd: ROOT, stdio: "ignore" });
    return `- ${name}: pass`;
  } catch {
    return `- ${name}: **FAIL** (\`${cmd}\`)`;
  }
};

const branch = git("branch --show-current") || "(detached)";
const head = git("log -1 --format=%h%x20%s");
const upstream = git("rev-parse --abbrev-ref --symbolic-full-name @{u}");
const aheadBehind = upstream ? git(`rev-list --left-right --count ${upstream}...HEAD`).split(/\s+/) : [];
const status = git("status --porcelain").split("\n").filter(Boolean);
const stashes = git("stash list").split("\n").filter(Boolean).length;
const recent = git("log -5 --format=%h%x20%s").split("\n").filter(Boolean);

const lines = [
  START,
  `_Refreshed ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC._`,
  "",
  `- Branch: \`${branch}\`${upstream ? ` (tracks \`${upstream}\`, ${aheadBehind[1] ?? 0} ahead / ${aheadBehind[0] ?? 0} behind)` : " (no upstream)"}`,
  `- HEAD: ${head || "(no commits)"}`,
  `- Uncommitted: ${status.length === 0 ? "none" : `${status.length} path(s)`}`,
  ...status.map((s) => `  - \`${s}\``),
  ...(stashes > 0 ? [`- Stashes: ${stashes} (\`git stash list\`; may be stale)`] : []),
  "- Recent commits:",
  ...recent.map((c) => `  - ${c}`),
];

if (args.has("--gates")) {
  lines.push(
    "- Gates:",
    "  " + gate("lint", "npm run lint"),
    "  " + gate("build", "npm run build"),
    "  " + gate("diff-check", "git diff --check"),
  );
} else {
  lines.push("- Gates: not run in this refresh (`npm run handoff -- --gates`)");
}
lines.push(END);
const snapshot = lines.join("\n");

const doc = fs.readFileSync(DOC, "utf8");
const s = doc.indexOf(START.slice(0, 20));
const e = doc.indexOf(END);
if (s === -1 || e === -1 || e < s) {
  console.error(`handoff: snapshot markers not found in ${path.relative(ROOT, DOC)}`);
  process.exit(1);
}
const updated = doc.slice(0, s) + snapshot + doc.slice(e + END.length);

if (args.has("--stdout")) {
  process.stdout.write(updated);
} else {
  fs.writeFileSync(DOC, updated);
  console.log(`handoff: snapshot refreshed in ${path.relative(ROOT, DOC)}`);
}
